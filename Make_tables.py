# Table 4: time-step refinement test
# ----------------------------------------------------------------------------
def table_refine(D, src):
    RS = D.get("refine_summary", {})
    regs = [r for r in REGIMES if r in RS and len(RS[r]) > 2]
    if not regs:
        return None
    eps_list = sorted({float(k) for r in regs for k in RS[r] if not k.startswith("max")},
                      reverse=True)
    lines = [tex_header(src),
             r"\begin{tabular}{@{}r@{\quad}" + "ccc" * len(regs) + r"@{}}",
             r"\toprule",
             r" & " + " & ".join(r"\multicolumn{3}{c}{regime %s}" % ROMAN[r] for r in regs) + r"\\",
             "".join(r"\cmidrule(lr){%d-%d}" % (2 + 3 * i, 4 + 3 * i) for i in range(len(regs))),
             r"$\eps$ & " + " & ".join([r"$\mathcal D_2$ & $\widehat K^{\eps}_N$ & "
                                        r"$\E|Z^{\eps}(T)|^{2}$"] * len(regs)) + r"\\",
             r"\midrule"]
    for eps in eps_list:
        row = [f"${eps:g}$"]
        for r in regs:
            c = RS[r].get(f"{eps}")
            if c is None:
                row += ["--"] * 3
                continue
            obs = [k for k in c if not k.startswith("_")]
            zD = max(abs(c[k]["zM2"]) for k in obs)
            zK = max(abs(c[k]["zKhat"]) for k in obs)
            zc = c["_coupling"]["z_strong_T"]
            row += [f"${zD:.2f}$", f"${zK:.2f}$", f"${zc:+.2f}$".replace("+", "\\phantom{-}")]
        lines.append(" & ".join(row) + r"\\")
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    return "\n".join(lines)


