# Table 3: reference values and their cross-validation
# ----------------------------------------------------------------------------
def table_ref(refs, val, reg, src):
    R = refs["reference_values"]
    regs = [r for r in REGIMES if r in R]
    col = lambda f: " & ".join(f(r) for r in regs)
    lines = [tex_header(src),
             r"\begin{tabular}{@{}l" + "c" * len(regs) + r"@{}}",
             r"\toprule",
             r" & " + " & ".join(f"regime {ROMAN[r]}" for r in regs) + r"\\",
             r"\midrule",
             r"\multicolumn{%d}{@{}l}{$\mathrm I^{0}=\E[f(V^{0}(T))]$}\\" % (1 + len(regs))]
    for k, e in reg.items():
        if e["in_table"]:
            lines.append(e["label"] + " & " + col(lambda r: f"${R[r][k]:.8f}$") + r"\\")
    lines.append(r"\midrule")
    lines.append(r"\multicolumn{%d}{@{}l}{checks of the density $p_T$}\\" % (1 + len(regs)))
    modes = val.get("modes", {})
    lines.append(r"modes of the spectral series & "
                 + col(lambda r: "--" if r == "I" else f"${modes.get(r, {}).get('n_modes', [N_MODES])[-1]}$")
                 + r"\\")
    lines.append(r"change of $\mathrm I^{0}$ from $30$ to $40$ modes & "
                 + col(lambda r: "--" if r == "I" else fmt_sci(modes.get(r, {}).get("max_change_30_40")))
                 + r"\\")
    tp = val.get("tpj12", {})
    lines.append(r"\eqref{eq:pI} against \cite[(2.10)]{TVJ10} & "
                 + col(lambda r: fmt_sci(val.get("regime_I_closed_form_max_abs_diff")) if r == "I" else "--")
                 + r"\\")
    lines.append(r"Laplace inversion \cite{TPJ12} & "
                 + col(lambda r: "--" if r == "I" or r not in tp else fmt_sci(tp[r]["max_abs_diff"]))
                 + r"\\")
    fv = val.get("fv", {})
    lines.append(r"finite volumes, $\max|p_T-p_T^{\rm FV}|$ & "
                 + col(lambda r: fmt_sci(fv.get(r, {}).get("max_abs_density_diff"))) + r"\\")
    lines.append(r"finite volumes, $\max_f|\mathrm I^{0}-\mathrm I^{0}_{\rm FV}|$ & "
                 + col(lambda r: fmt_sci(fv.get(r, {}).get("max_abs_I0_diff"))) + r"\\")
    nrm = val.get("normalisation", {})
    lines.append(r"$\int_\R p_T\,\dd v-1$ & "
                 + col(lambda r: fmt_sci(nrm.get(r, np.nan) - 1.0)) + r"\\")
    db = val.get("density_bound", {})
    lines.append(r"$\sup_v p_T(v)$ & " + col(lambda r: f"${db[r]['sup_p']:.3f}$") + r"\\")
    lines.append(r"bound \eqref{eq:M} on $M$ & " + col(lambda r: f"${db[r]['M_bound']:.3f}$") + r"\\")
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    return "\n".join(lines)


