def macros(D, reg, src, model=None):
    FIT = D["fits"]
    regs = [r for r in REGIMES if r in FIT]
    m = {}
    m["NumResultsNote"] = (r"\textcolor{red}{[quick test run, not for publication]}"
                           if D["meta"].get("quick") else "")
    m["NumFitWindow"] = f"{FIT[regs[0]]['fit_max']:g}"
    m["NumBiasWindow"] = f"{FIT[regs[0]].get('bias_max', 0.2):g}"
    ch = D["checks"]
    m["NumDCPmax"] = f"{ch['dcp_max_ratio']:.3f}"
    m["NumDCPviol"] = f"{ch['dcp_violations']:d}"
    m["NumIzeroMaxZ"] = f"{ch['I0_mc_max_abs_z']:.2f}"
    cells = [c for st in ("rate", "domain", "refine") for rr in D[st].values() for c in rr.values()]
    m["NumCells"] = f"{len(cells):d}"
    m["NumIzeroCount"] = f"{len(cells) * len(reg):d}"
    m["NumPathSteps"] = fmt_sci(sum(c["_coupling"]["N"] * c["_coupling"]["n_steps"]
                                    for c in cells)).strip("$")
    RS = D.get("refine_summary", {})
    zD = [RS[r]["max_abs_zM2"] for r in RS if "max_abs_zM2" in RS[r] and len(RS[r]) > 2]
    zK = [RS[r]["max_abs_zKhat"] for r in RS if "max_abs_zKhat" in RS[r] and len(RS[r]) > 2]
    m["NumRefineMaxZD"] = f"{max(zD):.2f}" if zD else "--"
    m["NumRefineMaxZK"] = f"{max(zK):.2f}" if zK else "--"
    zc, rc = [], []
    for r in RS:
        for ek, row in RS[r].items():
            if ek.startswith("max") or "_coupling" not in row:
                continue
            base = D["rate"].get(r, {}).get(ek)
            if base is None:
                continue
            zc.append(row["_coupling"]["z_strong_T"])
            rc.append(100.0 * row["_coupling"]["d_strong_T"] / base["_coupling"]["strong_T"])
    if zc:
        m["NumRefineCplZLo"] = f"{min(zc):.1f}"
        m["NumRefineCplZHi"] = f"{max(zc):.1f}"
        m["NumRefineCplRelLo"] = f"{min(rc):.1f}"
        m["NumRefineCplRelHi"] = f"{max(rc):.1f}"
    for r in regs:
        for q, name in (("strong_T", "CplT"), ("strong_sup", "CplSup")):
            c = FIT[r]["_coupling"][q]
            m[f"Num{name}{r}"] = fmt_par(c["slope_small"], c["slope_small_se"], math=False)
        f = FIT[r]["indicator"]
        m[f"NumInd{r}"] = fmt_par(f["slope_small_M2"], f["slope_small_M2_se"], math=False)
    # deviations from the prediction and excess over the benchmark, in standard errors
    dev, exc = [], []
    for k, e in reg.items():
        if not e["in_table"]:
            continue
        for r in regs:
            s, se = FIT[r][k]["slope_small_M2"], FIT[r][k]["slope_small_M2_se"]
            if not _ok(s, se) or se <= 0:
                continue
            dev.append(((s - e["predicted"]) / se, e["label"], r))
            if e["benchmark"] < e["predicted"] - 1e-9:
                exc.append(((s - e["benchmark"]) / se, e["label"], r))
    if dev:
        z, lab, r = max(dev, key=lambda t: abs(t[0]))
        m["NumMaxDevZ"] = f"{abs(z):.1f}"
        m["NumMaxDevWhere"] = f"{lab} in regime~{ROMAN[r]}"
        m["NumMeanDevZ"] = f"{np.mean([t[0] for t in dev]):+.2f}".replace("+", "")
        m["NumDevCount"] = f"{len(dev):d}"
        m["NumDevWithinTwo"] = f"{sum(abs(t[0]) <= 2 for t in dev):d}"
    if exc:
        z, lab, r = min(exc, key=lambda t: t[0])
        m["NumMinExcessZ"] = f"{z:.1f}"
        m["NumMinExcessWhere"] = f"{lab} in regime~{ROMAN[r]}"
        m["NumExcessTotal"] = f"{len(exc):d}"
        m["NumExcessAboveThree"] = f"{sum(t[0] > 3.0 for t in exc):d}"
    # group A: f_ind, f_1, f_sm (corrections of relative order eps expected);
    # group B: f_alpha, 0 < alpha < 1 (corrections of relative order eps^{|1-2 alpha|},
    # and a logarithm at alpha = 1/2): deficit = predicted - fitted exponent
    grpA, grpB = [], []
    for k, e in reg.items():
        if not e["in_table"]:
            continue
        inB = e["kind"] == "Holder" and e["alpha"] < 1.0
        for r in regs:
            s, se = FIT[r][k]["slope_small_M2"], FIT[r][k]["slope_small_M2_se"]
            if not _ok(s, se) or se <= 0:
                continue
            if inB:
                grpB.append((e["predicted"] - s, e["label"], r))
            else:
                grpA.append(((s - e["predicted"]) / se, e["label"], r))
    if grpA:
        z, lab, r = max(grpA, key=lambda t: abs(t[0]))
        m["NumMaxDevZA"] = f"{abs(z):.1f}"
        m["NumMaxDevWhereA"] = f"{lab} in regime~{ROMAN[r]}"
    if grpB:
        d, lab, r = max(grpB, key=lambda t: t[0])
        m["NumDefHiB"] = f"{d:.2f}"
        m["NumDefWhereB"] = f"{lab} in regime~{ROMAN[r]}"
        m["NumDefLoB"] = f"{min(t[0] for t in grpB):.2f}"
    # bias exponents (resolved ones)
    be = [FIT[r][k]["slope_bias"] for k, e in reg.items() if e["in_table"] for r in regs
          if FIT[r][k]["slope_bias"] is not None]
    nb = sum(1 for k, e in reg.items() if e["in_table"] for r in regs)
    m["NumBiasResolved"] = f"{len(be):d}"
    m["NumBiasTotal"] = f"{nb:d}"
    if be:
        m["NumBiasExpLo"] = f"{min(be):.2f}"
        m["NumBiasExpHi"] = f"{max(be):.2f}"
    # variance reduction for the indicator
    for tag, eps in (("Small", min(VR_TABLE_EPS)), ("Large", max(VR_TABLE_EPS))):
        vals = [(_cell(D, r, eps) or {}).get("indicator") for r in regs]
        vals = [v for v in vals if v is not None and _ok(v["var_ratio_K"])]
        if vals:
            rk = [v["var_ratio_K"] for v in vals]
            m[f"NumVR{tag}Eps"] = f"{eps:g}"
            m[f"NumVR{tag}Lo"] = f"{min(rk):.3g}"
            m[f"NumVR{tag}Hi"] = f"{max(rk):.3g}"
            m[f"NumGain{tag}"] = f"{min(1.0 / (2.0 * x) for x in rk if x > 0):.3g}"
            rj = [v["var_ratio_J"] for v in vals if np.isfinite(v["var_ratio_J"])]
            if rj:
                m[f"NumVRJ{tag}Lo"] = f"{min(rj):.3g}"
                m[f"NumVRJ{tag}Hi"] = f"{max(rj):.3g}"
            m[f"NumLam{tag}Lo"] = f"{min(v['lam'] for v in vals):.3f}"
            m[f"NumLam{tag}Hi"] = f"{max(v['lam'] for v in vals):.3f}"
    # variance ratio of the smooth anchor at the smallest eps of Table 2
    eps = min(VR_TABLE_EPS)
    vals = [(_cell(D, r, eps) or {}).get("smooth") for r in regs]
    vals = [v["var_ratio_K"] for v in vals if v is not None and _ok(v["var_ratio_K"])]
    if vals:
        m["NumVRSmoothSmallLo"] = fmt_sci(min(vals)).strip("$")
        m["NumVRSmoothSmallHi"] = fmt_sci(max(vals)).strip("$")
    # relative bias of the white-noise approximation for the indicator at eps = 0.2
    rb = []
    for r in regs:
        c = (_cell(D, r, 0.2) or {}).get("indicator")
        if c is not None and c["Khat"] != 0:
            rb.append(100.0 * abs(c["bias"]) / abs(c["Khat"]))
    if rb:
        m["NumRelBiasLo"] = f"{min(rb):.0f}"
        m["NumRelBiasHi"] = f"{max(rb):.0f}"
    m["NumDtRatio"] = f"{round(DT_SAFETY / DT_SAFETY_FINE):d}"
    # model computation (model_exponents.py): deficits expected on the fitting window
    if model is not None:
        dA, dB = [], []
        for r, rows in model["exponents"].items():
            for k, row in rows.items():
                e = reg.get(k)
                if e is None:
                    continue
                (dB if e["kind"] == "Holder" and e["alpha"] < 1.0 else dA).append(row["deficit"])
        if dB:
            m["NumModelDefLoB"] = f"{min(dB):.2f}"
            m["NumModelDefHiB"] = f"{max(dB):.2f}"
        if dA:
            m["NumModelDefMaxA"] = f"{max(abs(x) for x in dA):.2f}"
        zm = []
        for r, rows in model["exponents"].items():
            for k, row in rows.items():
                if r not in FIT or k not in FIT[r]:
                    continue
                sv, se = FIT[r][k]["slope_small_M2"], FIT[r][k]["slope_small_M2_se"]
                if _ok(sv, se) and se > 0:
                    zm.append(((sv - row["slope"]) / se, reg[k]["label"], r))
        if zm:
            z, lab, r = max(zm, key=lambda t: abs(t[0]))
            m["NumModelMaxZ"] = f"{abs(z):.1f}"
            m["NumModelMaxZWhere"] = f"{lab} in regime~{ROMAN[r]}"
    out = [tex_header(src)]
    out += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in m.items()]
    return "\n".join(out) + "\n", m


# ----------------------------------------------------------------------------
def write(path, text):
    with open(path, "w") as f:
        f.write(text)
    print(f"wrote {path}")


def main(argv=None):
    import argparse
    ap = argparse.ArgumentParser(description="Tables and macros of Section 5.")
    ap.add_argument("results", nargs="?", default=OUTPUT_FILE)
    ap.add_argument("--refs", default=REFERENCE_FILE)
    ap.add_argument("--validation", default=VALIDATION_FILE)
    ap.add_argument("--model", default="model_exponents.json",
                    help="output of model_exponents.py (optional)")
    ap.add_argument("--outdir", default=".")
    a = ap.parse_args(argv)
    os.makedirs(a.outdir, exist_ok=True)
    out = lambda name: os.path.join(a.outdir, name)
    reg = observable_registry()
    if os.path.exists(a.refs) and os.path.exists(a.validation):
        with open(a.refs) as f:
            refs = json.load(f)
        with open(a.validation) as f:
            val = json.load(f)
        write(out("tab_ref.tex"), table_ref(refs, val, reg, f"{os.path.basename(a.refs)}, "
                                                           f"{os.path.basename(a.validation)}"))
    else:
        print("[skip] tab_ref.tex: run observables.py and validate_reference.py first")
    if not os.path.exists(a.results):
        print(f"[skip] {a.results} not found: tab_fitted, tab_vr, tab_refine, results_macros")
        return
    with open(a.results) as f:
        D = json.load(f)
    src = os.path.basename(a.results)
    write(out("tab_fitted.tex"), table_fitted(D, reg, src))
    write(out("tab_vr.tex"), table_vr(D, src))
    t = table_refine(D, src)
    if t is not None:
        write(out("tab_refine.tex"), t)
