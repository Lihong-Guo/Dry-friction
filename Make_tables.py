# Table 2: variance reduction for the crossing indicator
# ----------------------------------------------------------------------------
def _cell(D, r, eps):
    for stage in ("rate", "domain"):
        c = D.get(stage, {}).get(r, {}).get(f"{eps}")
        if c is not None:
            return c
    return None


def table_vr(D, src, key="indicator"):
    regs = [r for r in REGIMES if r in D.get("rate", {})]
    lines = [tex_header(src),
             r"\begin{tabular}{@{}r@{\quad}cccccc@{}}",
             r"\toprule",
             r"$\eps$ & $\widehat K^{\eps}_N$ & $\E D^{\eps}$ & $\sigma_{\mathrm I^{\eps}}$ & "
             r"$\widehat\lambda^{\eps}_N$ & $\sigma^{2}_{J^{\eps}}/\sigma^{2}_{\mathrm I^{\eps}}$ & "
             r"$\sigma^{2}_{K^{\eps}}/\sigma^{2}_{\mathrm I^{\eps}}$\\"]
    for r in regs:
        I0 = None
        rows = []
        for eps in VR_TABLE_EPS:
            c = _cell(D, r, eps)
            if c is None:
                continue
            c = c[key]
            I0 = c["I0"]
            rows.append(" & ".join([
                f"${eps:g}$",
                fmt_par(c["Khat"], c["Khat_se"]),
                fmt_par(c["bias"], c["bias_se"]),
                fmt_g(np.sqrt(c["VarI"]), 3),
                fmt_par(c["lam"], c["lam_se"]),
                fmt_par(c["var_ratio_J"], c.get("var_ratio_J_se")),
                fmt_par(c["var_ratio_K"], c.get("var_ratio_K_se"))]) + r"\\")
        if not rows:
            continue
        lines.append(r"\midrule")
        lines.append(r"\multicolumn{7}{@{}l}{regime %s, \ $\mathrm I^{0}=%.6f$}\\"
                     % (ROMAN[r], I0))
        lines += rows
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    return "\n".join(lines)


