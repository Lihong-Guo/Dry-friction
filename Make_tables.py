r"""
Make_tables.py -- the tables of Section 5 and Appendix C and the numbers quoted in
the text of Section 5.4.

Inputs
  production_results.json  (Production_Run.py)       Tables 1, 2, 4 and the macros
  reference_values.json    (observables.py)          Table 3
  validation.json          (validate_reference.py)   Table 3
Outputs (each file holds a bare tabular, which the manuscript \input's inside its
table environment, so that captions and labels stay in the manuscript)
  tab_fitted.tex      Table 1: exponents of D_2, of the coupling errors and of the bias
  tab_vr.tex          Table 2: variance reduction for the crossing indicator
  tab_ref.tex         Table 3: reference values I^0 and their cross-validation
  tab_refine.tex      Table 4: time-step refinement test
  results_macros.tex  \newcommand's for the numbers quoted in Section 5.4
                      (including, if model_exponents.json exists, the model deficits)
Numbers in parentheses are standard errors in units of the last digit:
1.02(3) means 1.02 +- 0.03.

Without production_results.json only tab_ref.tex is written.
Usage: python Make_tables.py [production_results.json] [--outdir DIR]
Requires: numpy, params.py, observables.py.
"""
