def table_fitted(D, reg, src):
    FIT = D["fits"]
    regs = [r for r in REGIMES if r in FIT]
    lines = [tex_header(src),
             r"\setlength{\tabcolsep}{4.5pt}",
             r"\begin{tabular}{@{}lcc@{\quad}" + "c" * len(regs) + r"@{\quad}"
             + "c" * len(regs) + r"@{}}",
             r"\toprule",
             r" & \multicolumn{2}{c}{prediction} & \multicolumn{%d}{c}{exponent of "
             r"$\mathcal D_2(\eps)$} & \multicolumn{%d}{c}{exponent of $|\E D^{\eps}|$}\\"
             % (len(regs), len(regs)),
             r"\cmidrule(lr){2-3}\cmidrule(lr){4-%d}\cmidrule(l){%d-%d}"
             % (3 + len(regs), 4 + len(regs), 3 + 2 * len(regs)),
             r" & Thm.~\ref{thm:main} & bench. & " + " & ".join(ROMAN[r] for r in regs)
             + " & " + " & ".join(ROMAN[r] for r in regs) + r"\\",
             r"\midrule"]
    for k, e in reg.items():
        if not e["in_table"]:
            continue
        row = [e["label"], fmt_frac(e["predicted"]), fmt_frac(e["benchmark"])]
        row += [fmt_par(FIT[r][k]["slope_small_M2"], FIT[r][k]["slope_small_M2_se"])
                for r in regs]
        row += [fmt_par(FIT[r][k]["slope_bias"], FIT[r][k]["slope_bias_se"])
                for r in regs]
        lines.append(" & ".join(row) + r"\\")
    lines.append(r"\midrule")
    for q, lab, pred in (("strong_T", r"$\E|Z^{\eps}(T)|^{2}$", r"$2$"),
                         ("strong_sup", r"$\E\max_{m}|Z^{\eps}_m|^{2}$", r"$2^{*}$")):
        row = [lab, pred, "--"]
        row += [fmt_par(FIT[r]["_coupling"][q]["slope_small"],
                        FIT[r]["_coupling"][q]["slope_small_se"]) for r in regs]
        row += [""] * len(regs)
        lines.append(" & ".join(row) + r"\\")
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    return "\n".join(lines)


