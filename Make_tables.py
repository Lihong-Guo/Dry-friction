ROMAN = {"I": "(I)", "II": "(II)", "III": "(III)"}


# ----------------------------------------------------------------------------
# Formatting
# ----------------------------------------------------------------------------
def _ok(*xs):
    return all(x is not None and np.isfinite(x) for x in xs)


def fmt_par(v, se, math=True):
    """1.0234, 0.0312 -> '1.02(3)': the standard error in units of the last digit.
    The standard error is given with one significant digit, or with two when its
    three leading digits lie in 100..354 (the rounding rule of the Particle Data
    Group): 0.096 -> '(10)', 0.13 -> '(13)', 0.43 -> '(4)'.  Without a standard
    error, the value is printed with three significant digits."""
    if not _ok(v):
        return "--"
    if not _ok(se):
        s = f"{v:.3g}"
        return f"${s}$" if math else s
    if se <= 0:
        s = f"{v:.4g}"
    else:
        e = int(np.floor(np.log10(se)))
        lead = int(se / 10 ** (e - 2))            # three leading digits, 100..999
        if lead >= 950:                           # rounds up to 1000: two digits
            e, sig = e + 1, 2
        else:
            sig = 2 if lead <= 354 else 1
        d = max(sig - 1 - e, 0)
        r = int(round(se * 10 ** d))
        s = f"{v:.{d}f}({r})"
    return f"${s}$" if math else s


def fmt_frac(x):
    """2/3, 3/2, 5/3, 1, 2, ... as TeX."""
    if x is None:
        return "--"
    q = Fraction(float(x)).limit_denominator(12)
    return f"${q.numerator}$" if q.denominator == 1 else f"${q.numerator}/{q.denominator}$"


def fmt_sci(x, digits=1):
    r"""1.56e-7 -> "$1.6\cdot10^{-7}$";  0 -> "$0$"."""
    if x is None or not np.isfinite(x):
        return "--"
    if x == 0:
        return "$0$"
    e = int(np.floor(np.log10(abs(x))))
    m = x / 10 ** e
    if round(abs(m), digits) >= 10:
        m, e = m / 10, e + 1
    return f"${m:.{digits}f}\\cdot10^{{{e}}}$"


def fmt_g(x, n=3):
    return "--" if not _ok(x) else f"${x:.{n}g}$"


def tex_header(src):
    return f"% generated by Make_tables.py from {src}; do not edit\n"


